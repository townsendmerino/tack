// Package swiftgen emits Swift Codable types from internal/proto (DESIGN §9.3; ADR-001 records why tack has its own
// generator). It reflects over proto.Methods and proto.EventTypes, so it sees exactly what encoding/json sees: field
// names from json tags, omitempty, pointers. It is a stub until the app (P4): structs, optionals, arrays, string maps,
// a JSONValue for raw JSON, and the event payload as an enum keyed by the event type. Timestamps stay strings.
package swiftgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"reflect"
	"slices"
	"strings"
	"time"
	"unicode"

	"github.com/townsendmerino/tack/internal/proto"
)

// OutPath is where the generated file lives, relative to the repo root.
const OutPath = "apps/macos/Sources/TackProto/Proto.generated.swift"

var (
	rawType  = reflect.TypeFor[json.RawMessage]()
	timeType = reflect.TypeFor[time.Time]()
	evType   = reflect.TypeFor[proto.Event]()
)

// swiftKeywords are Go field names that, lower-cased, need backticks in Swift.
var swiftKeywords = map[string]bool{"protocol": true, "default": true, "case": true, "class": true, "struct": true,
	"enum": true, "func": true, "import": true, "in": true, "is": true, "let": true, "var": true, "where": true,
	"self": true, "init": true, "internal": true, "public": true, "return": true, "static": true}

// Generate returns the Swift source.
func Generate() []byte {
	g := &gen{named: map[string]reflect.Type{}, aliases: map[string]string{}}
	var roots []reflect.Type
	for _, m := range sortedKeys(proto.Methods) {
		spec := proto.Methods[m]
		roots = append(roots, spec.Params)
		if spec.Result != nil {
			roots = append(roots, spec.Result)
		}
	}
	for _, e := range sortedKeys(proto.EventTypes) {
		roots = append(roots, proto.EventTypes[e].Payload)
	}
	roots = append(roots, reflect.TypeFor[proto.Error]())
	for _, r := range roots {
		g.collect(r)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by `go run ./tools/protogen` from internal/proto. DO NOT EDIT.\n\n")
	b.WriteString("import Foundation\n\n")
	fmt.Fprintf(&b, "public enum TackProto {\n    public static let version = %d\n}\n\n", proto.Version)

	b.WriteString("public enum Method {\n")
	for _, m := range sortedKeys(proto.Methods) {
		fmt.Fprintf(&b, "    public static let %s = %q\n", methodIdent(m), m)
	}
	b.WriteString("}\n\n")

	for _, name := range sortedKeys(g.aliases) {
		fmt.Fprintf(&b, "public typealias %s = %s\n", name, g.aliases[name])
	}
	b.WriteString("\n")

	for _, name := range sortedKeys(g.named) {
		t := g.named[name]
		if t == evType {
			continue // emitted with the payload enum below
		}
		g.emitStruct(&b, t)
	}
	g.emitEvent(&b)
	b.WriteString(jsonValueSwift)
	return b.Bytes()
}

type gen struct {
	named   map[string]reflect.Type // struct types by Go name
	aliases map[string]string       // named non-struct types (SessionID) to their Swift type
}

func (g *gen) collect(t reflect.Type) {
	switch {
	case t == rawType || t == timeType:
		return
	case t.Kind() == reflect.Pointer, t.Kind() == reflect.Slice, t.Kind() == reflect.Map:
		g.collect(t.Elem())
	case t.Kind() == reflect.Struct:
		if _, seen := g.named[t.Name()]; seen {
			return
		}
		g.named[t.Name()] = t
		for _, f := range fields(t) {
			g.collect(f.Type)
		}
		if t == evType {
			for _, e := range proto.EventTypes {
				g.collect(e.Payload)
			}
		}
	case t.Name() != "" && t.PkgPath() != "":
		g.aliases[t.Name()] = basicSwift(t.Kind())
	}
}

func (g *gen) swiftType(t reflect.Type) string {
	switch {
	case t == rawType:
		return "JSONValue"
	case t == timeType:
		return "String" // RFC 3339 with fractional seconds, as Go writes it
	case t.Kind() == reflect.Pointer:
		return g.swiftType(t.Elem()) + "?"
	case t.Kind() == reflect.Slice:
		return "[" + g.swiftType(t.Elem()) + "]"
	case t.Kind() == reflect.Map:
		return "[String: " + g.swiftType(t.Elem()) + "]"
	case t.Kind() == reflect.Struct || (t.Name() != "" && t.PkgPath() != ""):
		return t.Name()
	}
	return basicSwift(t.Kind())
}

func basicSwift(k reflect.Kind) string {
	switch k {
	case reflect.String:
		return "String"
	case reflect.Bool:
		return "Bool"
	case reflect.Int, reflect.Int32:
		return "Int"
	case reflect.Int64:
		return "Int64"
	case reflect.Float64:
		return "Double"
	}
	panic(fmt.Sprintf("swiftgen: no Swift type for kind %s", k))
}

type field struct {
	Go, JSON  string
	Type      reflect.Type
	OmitEmpty bool
}

func fields(t reflect.Type) []field {
	var out []field
	for f := range t.Fields() {
		tag := f.Tag.Get("json")
		if !f.IsExported() || tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name
		}
		out = append(out, field{Go: f.Name, JSON: name, Type: f.Type, OmitEmpty: strings.Contains(opts, "omitempty")})
	}
	return out
}

func (g *gen) emitStruct(b *bytes.Buffer, t reflect.Type) {
	fs := fields(t)
	fmt.Fprintf(b, "public struct %s: Codable, Equatable, Sendable {\n", t.Name())
	for _, f := range fs {
		typ := g.swiftType(f.Type)
		if f.OmitEmpty && !strings.HasSuffix(typ, "?") {
			typ += "?" // Go omits the zero value, so the key may be absent
		}
		fmt.Fprintf(b, "    public var %s: %s\n", prop(f.Go), typ)
	}
	b.WriteString("\n    enum CodingKeys: String, CodingKey {\n")
	for _, f := range fs {
		fmt.Fprintf(b, "        case %s = %q\n", prop(f.Go), f.JSON)
	}
	b.WriteString("    }\n}\n\n")
}

// emitEvent writes Event with its payload decoded by type into EventPayload, and unknown types kept as raw JSON so an
// older client survives a newer daemon.
func (g *gen) emitEvent(b *bytes.Buffer) {
	evs := sortedKeys(proto.EventTypes)
	b.WriteString("public enum EventPayload: Equatable, Sendable {\n")
	for _, e := range evs {
		fmt.Fprintf(b, "    case %s(%s)\n", eventCase(e), proto.EventTypes[e].Payload.Name())
	}
	b.WriteString("    case unknown(JSONValue)\n}\n\n")

	b.WriteString("public struct Event: Codable, Equatable, Sendable {\n")
	var keys []field
	for _, f := range fields(evType) {
		typ := g.swiftType(f.Type)
		if f.Go == "Payload" {
			typ = "EventPayload"
		} else if f.OmitEmpty {
			typ += "?"
		}
		fmt.Fprintf(b, "    public var %s: %s\n", prop(f.Go), typ)
		keys = append(keys, f)
	}
	b.WriteString("\n    enum CodingKeys: String, CodingKey {\n")
	for _, f := range keys {
		fmt.Fprintf(b, "        case %s = %q\n", prop(f.Go), f.JSON)
	}
	b.WriteString("    }\n\n")
	b.WriteString("    public init(from decoder: Decoder) throws {\n")
	b.WriteString("        let c = try decoder.container(keyedBy: CodingKeys.self)\n")
	for _, f := range keys {
		if f.Go == "Payload" {
			continue
		}
		fn := "decode"
		typ := g.swiftType(f.Type)
		if f.OmitEmpty {
			fn = "decodeIfPresent"
		}
		fmt.Fprintf(b, "        %s = try c.%s(%s.self, forKey: .%s)\n", prop(f.Go), fn, typ, prop(f.Go))
	}
	b.WriteString("        switch type {\n")
	for _, e := range evs {
		fmt.Fprintf(b, "        case %q: payload = .%s(try c.decode(%s.self, forKey: .payload))\n",
			string(e), eventCase(e), proto.EventTypes[e].Payload.Name())
	}
	b.WriteString("        default: payload = .unknown(try c.decode(JSONValue.self, forKey: .payload))\n        }\n    }\n\n")
	b.WriteString("    public func encode(to encoder: Encoder) throws {\n")
	b.WriteString("        var c = encoder.container(keyedBy: CodingKeys.self)\n")
	for _, f := range keys {
		if f.Go == "Payload" {
			continue
		}
		fn := "encode"
		if f.OmitEmpty {
			fn = "encodeIfPresent"
		}
		fmt.Fprintf(b, "        try c.%s(%s, forKey: .%s)\n", fn, prop(f.Go), prop(f.Go))
	}
	b.WriteString("        switch payload {\n")
	for _, e := range evs {
		fmt.Fprintf(b, "        case .%s(let p): try c.encode(p, forKey: .payload)\n", eventCase(e))
	}
	b.WriteString("        case .unknown(let v): try c.encode(v, forKey: .payload)\n        }\n    }\n}\n\n")
}

// prop is a Go field name as a Swift property: lower camel case, backticked if it is a keyword.
func prop(goName string) string {
	r := []rune(goName)
	i := 0
	for i < len(r) && unicode.IsUpper(r[i]) && (i == 0 || i+1 >= len(r) || unicode.IsUpper(r[i+1])) {
		r[i] = unicode.ToLower(r[i])
		i++
	}
	s := string(r)
	if swiftKeywords[s] {
		return "`" + s + "`"
	}
	return s
}

// eventCase is an event type as an enum case: "tool.finished" → toolFinished.
func eventCase(e proto.EventType) string {
	parts := strings.FieldsFunc(string(e), func(r rune) bool { return r == '.' || r == '_' })
	for i := 1; i < len(parts); i++ {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	s := strings.Join(parts, "")
	if swiftKeywords[s] {
		return "`" + s + "`"
	}
	return s
}

// methodIdent is a method name as a Swift identifier: "session/new" → sessionNew.
func methodIdent(m string) string {
	parts := strings.Split(m, "/")
	for i := 1; i < len(parts); i++ {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

func sortedKeys[K ~string, V any](m map[K]V) []K {
	out := make([]K, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

const jsonValueSwift = `/// Any JSON value: tool inputs and other raw JSON the protocol carries without a fixed shape.
public enum JSONValue: Codable, Equatable, Sendable {
    case null
    case bool(Bool)
    case number(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])

    public init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if c.decodeNil() { self = .null }
        else if let v = try? c.decode(Bool.self) { self = .bool(v) }
        else if let v = try? c.decode(Double.self) { self = .number(v) }
        else if let v = try? c.decode(String.self) { self = .string(v) }
        else if let v = try? c.decode([JSONValue].self) { self = .array(v) }
        else { self = .object(try c.decode([String: JSONValue].self)) }
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .null: try c.encodeNil()
        case .bool(let v): try c.encode(v)
        case .number(let v): try c.encode(v)
        case .string(let v): try c.encode(v)
        case .array(let v): try c.encode(v)
        case .object(let v): try c.encode(v)
        }
    }
}
`
